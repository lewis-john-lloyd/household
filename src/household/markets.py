def history():
    """{year: (stocks, bonds, inflation)} as fractions."""
    return {y: (s / 100, b / 100, CPI[y] / CPI[y - 1] - 1) for y, (s, _, b) in RETURNS.items()}


def real_series(stock_share):
    """(years, real portfolio returns) for a portfolio rebalanced each year to stock_share in stocks and the
    rest in ten-year Treasuries."""
    years = sorted(RETURNS)
    h = history()
    out = np.array([(1 + stock_share * h[y][0] + (1 - stock_share) * h[y][1]) / (1 + h[y][2]) - 1 for y in years])
    return np.array(years), out
